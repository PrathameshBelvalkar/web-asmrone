/* global fetch, process */
// Writes src/config/model-catalog.ts from the Hugging Face API, so no hash is typed by hand.
// Usage: node scripts/update-model-catalog.mjs > src/config/model-catalog.ts
// Each model is pinned to the commit the repository had when this ran.

const WHISPER_REPO = 'ggerganov/whisper.cpp';
const VAD_REPO = 'ggml-org/whisper-vad';

const MODELS = [
  {
    id: 'large-v3-turbo-q5_0',
    title: 'Best quality',
    note: 'For computers with a graphics card or an Apple chip',
    file: 'ggml-large-v3-turbo-q5_0.bin',
  },
  {
    id: 'medium-q5_0',
    title: 'Good quality',
    note: 'Strong processor, no usable graphics card',
    file: 'ggml-medium-q5_0.bin',
  },
  {
    id: 'small-q5_1',
    title: 'Fastest',
    note: 'Older or weaker computers',
    file: 'ggml-small-q5_1.bin',
  },
];
const VAD_FILE = 'ggml-silero-v5.1.2.bin';

async function getJson(url) {
  const res = await fetch(url, { headers: { accept: 'application/json' } });
  if (!res.ok) throw new Error(`${url} answered ${res.status}`);
  return res.json();
}

/** Resolves the commit and, for each wanted file, its SHA-256 and size (from Git LFS metadata). */
async function resolveFiles(repo, files) {
  const info = await getJson(`https://huggingface.co/api/models/${repo}`);
  const tree = await getJson(`https://huggingface.co/api/models/${repo}/tree/main`);
  const byPath = new Map(tree.map((entry) => [entry.path, entry]));
  return files.map((file) => {
    const lfs = byPath.get(file)?.lfs;
    if (!lfs) throw new Error(`${repo} has no LFS file named ${file}`);
    return {
      file,
      url: `https://huggingface.co/${repo}/resolve/${info.sha}/${file}`,
      sha256: lfs.oid,
      size: lfs.size,
    };
  });
}

function entryLiteral(model, resolved, indent) {
  const pad = ' '.repeat(indent);
  const lines = [
    `${pad}{`,
    `${pad}  id: '${model.id}',`,
    model.title ? `${pad}  title: '${model.title}',` : null,
    model.note ? `${pad}  note: '${model.note}',` : null,
    `${pad}  file: '${resolved.file}',`,
    `${pad}  url: '${resolved.url}',`,
    `${pad}  sha256: '${resolved.sha256}',`,
    `${pad}  size: ${resolved.size},`,
    `${pad}},`,
  ];
  return lines.filter((line) => line !== null).join('\n');
}

const whisper = await resolveFiles(
  WHISPER_REPO,
  MODELS.map((m) => m.file),
);
const vad = (await resolveFiles(VAD_REPO, [VAD_FILE]))[0];

const modelEntries = MODELS.map((model, i) => entryLiteral(model, whisper[i], 2)).join('\n');
const vadEntry = entryLiteral(
  { id: 'silero-v5.1.2', title: 'Voice detection', note: 'Finds where people speak' },
  vad,
  0,
).replace(/,$/, ';');

process.stdout.write(`/** Speech models for AI subtitles. Generated by scripts/update-model-catalog.mjs. */
export interface ModelEntry {
  readonly id: string;
  readonly title: string;
  readonly note: string;
  readonly file: string;
  /** Pinned to a commit, not "main". */
  readonly url: string;
  readonly sha256: string;
  /** Bytes. */
  readonly size: number;
}

export const MODELS: readonly ModelEntry[] = [
${modelEntries}
];

export const VAD_MODEL: ModelEntry = ${vadEntry}
`);
